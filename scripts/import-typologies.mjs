import { readdirSync, mkdirSync, copyFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';

// Usage: node scripts/import-typologies.mjs /path/to/extracted-zip-folders
const source = process.argv[2];
if (!source) throw new Error('Provide the directory containing the extracted typology folders.');
const assets = [];
const provenance = [];
const states = { A: 'furnished', E: 'unfurnished', CAD: 'plans' };
for (const folder of readdirSync(source).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)))) {
  const type = folder.match(/^(T\d+) - /)?.[1];
  if (!type) continue;
  const input = join(source, folder);
  const output = join('public/plants/details/20261117', type);
  const save = async (file, key) => {
    const destination = join(output, key);
    mkdirSync(join(destination, '..'), { recursive: true });
    if (key.endsWith('.webp')) await sharp(file).webp({ quality: 88 }).toFile(destination);
    else copyFileSync(file, destination);
    assets.push(`plants/details/20261117/${type}/${key}`);
    provenance.push({ source: file.slice(source.length + 1), asset: `plants/details/20261117/${type}/${key}` });
  };
  for (const name of readdirSync(input)) {
    const match = name.match(/^(CAD|AMOBLADO|ENTREGABLE)_.*?(?:_(1|2)PISO)?\.jpg$/i);
    if (match) {
      const state = { CAD: 'plans', AMOBLADO: 'furnished', ENTREGABLE: 'unfurnished' }[match[1]];
      await save(join(input, name), `${state}${match[2] === '2' ? '_2floor' : ''}.webp`);
    } else if (/^GALER[IÍ]A$/i.test(name)) {
      for (const file of readdirSync(join(input, name))) {
        if (/^\d+\.(jpg|png)$/i.test(file)) await save(join(input, name, file), `gallery/${parseInt(file)}.webp`);
      }
    } else if (name === 'TRANSICIONES') {
      const seen = new Set();
      for (const file of readdirSync(join(input, name))) {
        const transition = file.match(/ - (\d+)_(CAD|A|E)_a_(CAD|A|E)/i);
        if (!transition) throw new Error(`Unknown transition: ${file}`);
        let [, number, from, to] = transition;
        // T10's 02 file is mislabeled CAD_a_A; its first frame is furnished.
        if (type === 'T10' && number === '02') { from = 'A'; to = 'CAD'; }
        const floor = type === 'T14' ? (file.startsWith('T14.2') ? '_2floor' : '_1floor') : '';
        const key = `transitions/${states[from]}_to_${states[to]}${floor}.mp4`;
        if (seen.has(key)) throw new Error(`Duplicate transition: ${type}/${key}`);
        seen.add(key);
        await save(join(input, name, file), key);
      }
      if (seen.size !== (type === 'T14' ? 12 : 6)) throw new Error(`Incomplete transitions: ${type}`);
    }
  }
}
assets.sort();
writeFileSync('src/data/updated-typology-assets.ts', '// Generated by scripts/import-typologies.mjs from the supplied November 17 assets.\nexport const updatedTypologyAssets: string[] = ' + JSON.stringify(assets, null, 2) + ';\n');
mkdirSync('docs/assets', { recursive: true });
writeFileSync('docs/assets/typologies-20261117.json', JSON.stringify(provenance, null, 2) + '\n');
console.log(`Prepared ${assets.length} typology assets.`);
